"""Stage a LONI GPU package that fine-tunes MACE-matpes-r2scan on the chirality labels (MBA2PbI4, packages 105 + 113).

    python examples/scripts/make_chirality_finetune_package.py --dataset data/training/chirality_v1 \
        --foundation D:/MLIP_Foundational_Models/mace/MACE-matpes-r2scan-omat-ft.model \
        --out <LONI_staging>/chiral_ft1_mace_mba2pbi4

Sibling of make_prerelax_package.py (same cluster layout: one gpu2 GPU, conda mace_env, foundation and data hashes
checked in the job, --restart_latest) for an export_chirality_training.py dataset (schema pvpass_training/1, D3
subtracted). The training settings come from examples/chirality/finetune_overrides.json, the same file the local
pilot path uses. The cluster job only trains and lets mace_run_train report its own test-set table; the acceptance
scoring (score_chirality_mlip.py: per-environment forces, rotor profiles, R - rac with D3 added back) runs on the
PV_Passivator machine after export, because it needs pvpassivator.chirality.
Nothing is submitted. The package number comes from the LONI desk.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OVERRIDES = ROOT / "examples" / "chirality" / "finetune_overrides.json"
CLUSTER_FOUNDATION = ("/ddnB/project/ramu/lgutsev/MLIP_PROJECT_STORAGE/MLIP_Foundational_Models/mace/"
                      "MACE-matpes-r2scan-omat-ft.model")
YAML_KEYS = ("name", "seed", "E0s", "energy_weight", "forces_weight", "lr", "batch_size", "valid_batch_size",
             "max_num_epochs", "patience")


def sha256(path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def lf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def config_yaml(ov: dict, foundation: str, target: str) -> str:
    v = {k: ov[k] for k in YAML_KEYS}
    return f"""# mace_run_train config for the MBA2PbI4 chirality fine-tune (generated by make_chirality_finetune_package.py)
name: {v['name']}
seed: {v['seed']}
foundation_model: {foundation}
multiheads_finetuning: false      # naive fine-tune; no replay of the foundation's training set
E0s: {v['E0s']}                   # two crystals of one composition: per-element references are not identifiable
train_file: data/train.extxyz
valid_file: data/valid.extxyz
test_file: data/test.extxyz
energy_key: REF_energy            # {target}
forces_key: REF_forces
loss: weighted
energy_weight: {v['energy_weight']}
forces_weight: {v['forces_weight']}              # the zero-shot failure is in forces (C, N, axial I)
stress_weight: 0.0
compute_stress: false
lr: {v['lr']}
batch_size: {v['batch_size']}
valid_batch_size: {v['valid_batch_size']}
max_num_epochs: {v['max_num_epochs']}
patience: {v['patience']}
eval_interval: 1
ema: true
ema_decay: 0.99
amsgrad: true
clip_grad: 1.0
default_dtype: float64
device: cuda
restart_latest: true
save_cpu: true
work_dir: run
"""


SLURM = """#!/bin/bash
#SBATCH --job-name=chiral-ft1
#SBATCH --account={account}
#SBATCH --partition={partition}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=8
#SBATCH --gres=gpu:1
#SBATCH --time={time}
#SBATCH --output=logs/%x_%j.out
# {package}: fine-tune MACE-matpes-r2scan-omat-ft on the MBA2PbI4 r2SCAN(+D3 subtracted) labels of packages 105 + 113.
# Generated by PV_Passivator examples/scripts/make_chirality_finetune_package.py; nothing was submitted by the generator.
set -eo pipefail
cd "$SLURM_SUBMIT_DIR"
mkdir -p logs run results
rm -f results/DONE results/FAILED
trap 'echo "failed at line $LINENO (see results/train.log)" > results/FAILED' ERR
# conda's activation scripts read unset variables: -u only after them
module purge
source /home/lgutsev/miniforge3/etc/profile.d/conda.sh
conda activate "${{CHIRAL_MACE_ENV:-{env}}}"
set -u
export PYTHONNOUSERSITE=1 TORCHDYNAMO_DISABLE=1 OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK
{{ hostname; date; nvidia-smi --query-gpu=name,memory.total --format=csv; }} > results/info.txt
python -c "import mace, torch; print('mace', mace.__version__, 'torch', torch.__version__, 'cuda', torch.cuda.is_available())" | tee results/env.txt
[ -s "{foundation}" ] || {{ echo "foundation checkpoint missing: {foundation}" >&2; exit 2; }}
echo "{foundation_sha}  {foundation}" | sha256sum -c - || {{ echo "foundation checkpoint hash differs" >&2; exit 2; }}
( cd data && sha256sum -c SHA256SUMS ) || {{ echo "data/ missing or changed" >&2; exit 2; }}
start=$(date +%s)
mace_run_train --config finetune.yaml 2>&1 | tee -a results/train.log
MODEL=$(ls -t run/{name}*.model 2>/dev/null | grep -v compiled | head -1 || true)
[ -n "$MODEL" ] || {{ echo "no trained model in run/" >&2; exit 1; }}
cp "$MODEL" results/
sha256sum "$MODEL" > results/model.sha256
grep -A8 "Error-table on" results/train.log > results/error_table.txt || true
{{ date; echo "wall_s $(( $(date +%s) - start ))"; }} > results/DONE
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", type=Path, required=True)
    ap.add_argument("--foundation", type=Path, required=True, help="local checkpoint (hashed here)")
    ap.add_argument("--foundation-on-cluster", default=CLUSTER_FOUNDATION)
    ap.add_argument("--overrides", type=Path, default=OVERRIDES)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--account", default="loni_perovsk27")
    ap.add_argument("--partition", default="gpu2")
    ap.add_argument("--time", default="08:00:00")
    ap.add_argument("--env", default="/project/lgutsev/env/mace_env")
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args(argv)
    for p in (a.foundation_on_cluster, a.env):
        if not p.startswith("/") or ":" in p:   # Git Bash rewrites /ddnB/... to C:/Program Files/Git/ddnB/...
            raise SystemExit(f"cluster path must be absolute POSIX: {p} (in Git Bash set MSYS_NO_PATHCONV=1)")
    ds, out = a.dataset, a.out
    rep = json.loads((ds / "dataset.json").read_text())
    if rep.get("schema") != "pvpass_training/1" or not rep.get("d3_subtracted") or not rep.get("ready_for_pilot"):
        raise SystemExit("need a pvpass_training/1 export with D3 subtracted and train + valid splits")
    for split, rec in rep["files"].items():
        if sha256(ds / rec["file"]) != rec["sha256"]:
            raise SystemExit(f"{split}: data changed since export")
        if not rec["frames"]:
            raise SystemExit(f"{split} split is empty")
    if out.exists():
        if not a.overwrite:
            raise SystemExit(f"{out} exists (use --overwrite)")
        shutil.rmtree(out)
    ov = json.loads(a.overrides.read_text())
    fsha = sha256(a.foundation)
    lf(out / "finetune.yaml", config_yaml(ov, a.foundation_on_cluster, rep["target"]))
    lf(out / "run_chiral_ft1.slurm", SLURM.format(account=a.account, partition=a.partition, time=a.time, package=out.name,
                                                  env=a.env, foundation=a.foundation_on_cluster, foundation_sha=fsha,
                                                  name=ov["name"]))
    (out / "data").mkdir(parents=True)
    sums = []
    for f in ("train.extxyz", "valid.extxyz", "test.extxyz", "dataset.json"):
        shutil.copyfile(ds / f, out / "data" / f)
        sums.append(f"{sha256(out / 'data' / f)}  {f}")
    lf(out / "data" / "SHA256SUMS", "\n".join(sums) + "\n")
    lf(out / "export.list", "results/*\nlogs/*\nrun/*.log\nrun/results/*\n")
    files = rep["files"]
    size_mb = sum((out / "data" / f).stat().st_size for f in ("train.extxyz", "valid.extxyz", "test.extxyz")) / 1e6
    lf(out / "README.md", f"""# {out.name}: MACE fine-tune for the MBA2PbI4 chirality benchmark

**What it is.** A naive fine-tune of `{a.foundation.name}` on r2SCAN+D3(BJ) labels of (R)- and (rac)-MBA2PbI4
(LONI packages 105 rev1 and 113). The foundation model failed the fixed acceptance criteria on these crystals
(force RMSE 0.14-0.18 eV/A on C, N and axial I; R - rac 35/40 vs 51/75 meV per f.u.). The fine-tuned model is a
candidate only: it is accepted or rejected on the PV_Passivator machine against the same criteria, never on this job's
own numbers.

**Data** (`data/`, {size_mb:.1f} MB, in the package): train {files['train']['frames']}, valid {files['valid']['frames']},
test {files['test']['frames']} frames, split by whole scan / seed / trajectory (examples/chirality/finetune_splits.json).
Target: {rep['target']}. **At inference add D3(BJ, r2SCAN) back.**

**Foundation checkpoint on LONI:** `{a.foundation_on_cluster}` (sha256 `{fsha}`). Upload it once if absent; the job
checks the hash and downloads nothing.

**Run:** `mkdir -p logs && sbatch run_chiral_ft1.slurm` (1 x {a.partition} GPU, <= {a.time}; {ov['max_num_epochs']}
epochs max, patience {ov['patience']}, `restart_latest`, so a resubmission resumes). Env `{a.env}` (`CHIRAL_MACE_ENV`
overrides); results/env.txt records the mace, torch and CUDA versions (written for mace-torch 0.3.16).
Estimate: 1-3 GPU-h [I]. Measured on the laptop GPU (8 GB, float64): 3.9 min per epoch for 24 frames of 188 atoms,
i.e. ~8-10 h for 60 epochs of this set there; a gpu2 GPU should be several times faster.

**Done when** `results/DONE` exists; `results/FAILED` names the failing line otherwise.
**Export:** results/* (model copy, model.sha256, train.log, error_table.txt, env/info), logs/*, run/*.log.
""")
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    except OSError:
        commit = None
    meta = {"package": out.name, "status": "staged, not submitted", "generator": "examples/scripts/make_chirality_finetune_package.py",
            "generator_commit": commit, "dataset": str(ds), "dataset_files": files, "overrides": ov,
            "foundation_local": str(a.foundation), "foundation_cluster": a.foundation_on_cluster, "foundation_sha256": fsha,
            "files_sha256": {p.relative_to(out).as_posix(): sha256(p) for p in sorted(out.rglob("*")) if p.is_file()}}
    lf(out / "package.json", json.dumps(meta, indent=1) + "\n")
    print(json.dumps({"package": str(out), "data_MB": round(size_mb, 1), "frames": {k: v["frames"] for k, v in files.items()}}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
