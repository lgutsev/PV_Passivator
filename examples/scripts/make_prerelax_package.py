"""Draft a LONI GPU package that fine-tunes a MACE foundation model into a PRE-RELAXER (not a label model).

    python examples/scripts/make_prerelax_package.py --dataset data/prerelax_a0/dataset_v1 \
        --foundation D:/MLIP_Foundational_Models/mace/MACE-matpes-r2scan-omat-ft.model \
        --foundation-on-cluster /project/lgutsev/MLIP_PROJECT_STORAGE/MLIP_Foundational_Models/mace/MACE-matpes-r2scan-omat-ft.model \
        --out data/prerelax_a0/NN_mace_pvpass_prerelax_a0 [--epochs 60]

Input: an export_prerelax_frames.py dataset (schema pvpass_prerelax/1, label_grade false). The package holds:
  finetune.yaml          mace_run_train config: naive fine-tune (no multihead replay), E0s from the foundation,
                         force-weighted loss; the target is DFT minus D3 when the dataset says so
  run_finetune.slurm     one gpu2 task: checks data hashes and the env, trains (--restart_latest), evaluates
  evaluate_prerelax.py   force RMSE / cosine on the held-out test jobs vs the dataset's REF_forces
  data/                  the dataset + SHA256SUMS; NOT for git: the owner copies it to the cluster
  README.md, export.list, package.json (every file's sha256, the generator commit)
Nothing is submitted. The package number comes from the LONI desk; NN in the folder name is a placeholder.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
from pathlib import Path


def sha256(path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def lf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


