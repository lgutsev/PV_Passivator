EVAL = '''"""Force metrics of a MACE model on an exported pre-relax split, vs its REF_forces (same target convention).
    python evaluate_prerelax.py --model M.model --data data/test.extxyz --out results/test_metrics.json"""
import argparse, json
import numpy as np
from ase.io import read


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True); ap.add_argument("--data", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--device", default="cuda")
    a = ap.parse_args()
    from mace.calculators import MACECalculator
    calc = MACECalculator(model_paths=a.model, device=a.device, default_dtype="float64")
    per_job, rows = {}, []
    for at in read(a.data, index=":"):
        ref = at.arrays["REF_forces"]; e_ref = at.info["REF_energy"]
        b = at.copy(); b.calc = calc
        f = b.get_forces(); e = b.get_potential_energy()
        nr, nf = np.linalg.norm(ref, axis=1), np.linalg.norm(f, axis=1)
        big = nr > 0.05
        cos = ((f * ref).sum(1) / np.maximum(nr * nf, 1e-9))[big]
        rows.append({"job": at.info.get("job"), "frame": at.info.get("frame"), "source": at.info.get("source"),
                     "f_rmse": float(np.sqrt(((f - ref) ** 2).mean())), "fmax_ref": float(nr.max()), "fmax_ml": float(nf.max()),
                     "cos_big": float(cos.mean()) if big.any() else None, "n_big": int(big.sum()),
                     "e_err_per_atom": float((e - e_ref) / len(at))})
    for r in rows:
        per_job.setdefault(r["job"], []).append(r)
    summary = {}
    for job, rs in per_job.items():
        e = np.array([r["e_err_per_atom"] for r in rs])
        summary[job] = {"frames": len(rs), "f_rmse": float(np.sqrt(np.mean([r["f_rmse"] ** 2 for r in rs]))),
                        "cos_big": float(np.nanmean([r["cos_big"] for r in rs if r["cos_big"] is not None])),
                        "f_rmse_last10": float(np.sqrt(np.mean([r["f_rmse"] ** 2 for r in rs[-10:]]))),
                        "cos_big_last10": float(np.nanmean([r["cos_big"] for r in rs[-10:] if r["cos_big"] is not None])),
                        "e_err_per_atom_std_meV": float(1000 * e.std())}   # constant offsets are irrelevant to relaxation
    acceptance = {"f_rmse_max": 0.03, "cos_big_min": 0.9}
    passed = bool(all(s["f_rmse_last10"] <= acceptance["f_rmse_max"] and s["cos_big_last10"] >= acceptance["cos_big_min"]
                 for s in summary.values()))
    json.dump({"model": a.model, "data": a.data, "summary": summary, "acceptance": acceptance, "passed": passed,
               "frames": rows}, open(a.out, "w"), indent=1, default=lambda o: o.item() if hasattr(o, "item") else str(o))
    print(json.dumps({"summary": summary, "passed": passed}, indent=1))


if __name__ == "__main__":
    main()
'''


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--foundation", required=True, help="local checkpoint (hashed here)")
    ap.add_argument("--foundation-on-cluster", required=True, help="the same checkpoint's path on the cluster")
    ap.add_argument("--out", required=True)
    ap.add_argument("--epochs", type=int, default=60)
    ap.add_argument("--seed", type=int, default=17)
    ap.add_argument("--account", default="loni_perovsk27")
    ap.add_argument("--partition", default="gpu2")
    ap.add_argument("--time", default="12:00:00")
    ap.add_argument("--env", default="/project/lgutsev/env/mace_env")
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args(argv)
    for p in (a.foundation_on_cluster, a.env):
        if not p.startswith("/") or ":" in p:   # Git Bash rewrites /ddnB/... to C:/Program Files/Git/ddnB/...
            raise SystemExit(f"cluster path must be absolute POSIX: {p} (in Git Bash set MSYS_NO_PATHCONV=1)")
    ds, out = Path(a.dataset), Path(a.out)
    rep = json.loads((ds / "dataset.json").read_text())
    if rep.get("schema") != "pvpass_prerelax/1" or rep.get("label_grade") is not False:
        raise SystemExit("dataset is not a pvpass_prerelax/1 (label_grade false) export")
    for split, rec in rep["files"].items():
        if sha256(ds / rec["file"]) != rec["sha256"]:
            raise SystemExit(f"{split}: data changed since export")
        if split in ("train", "valid", "test") and not rec["frames"]:
            raise SystemExit(f"{split} split is empty")
    if out.exists():
        if not a.overwrite:
            raise SystemExit(f"{out} exists (use --overwrite)")
        shutil.rmtree(out)
    pkg = out.name
    name = "pvpass_prerelax_a0"
    fsha = sha256(a.foundation)
    target = rep["target"]
    lf(out / "finetune.yaml", CONFIG.format(name=name, seed=a.seed, foundation=a.foundation_on_cluster, target=target,
                                            epochs=a.epochs, patience=max(10, a.epochs // 4)))
    lf(out / "run_finetune.slurm", SLURM.format(short=pkg.split("_")[0], account=a.account, partition=a.partition,
                                                time=a.time, package=pkg, foundation_name=Path(a.foundation).name,
                                                env=a.env, foundation=a.foundation_on_cluster, foundation_sha=fsha,
                                                name=name))
    lf(out / "evaluate_prerelax.py", EVAL)
    (out / "data").mkdir(parents=True)
    sums = []
    for f in ("train.extxyz", "valid.extxyz", "test.extxyz", "dataset.json"):
        shutil.copyfile(ds / f, out / "data" / f)
        sums.append(f"{sha256(out / 'data' / f)}  {f}")
    lf(out / "data" / "SHA256SUMS", "\n".join(sums) + "\n")
    lf(out / "export.list", "results/*\nlogs/*\nrun/*.model\nrun/*.log\nrun/results/*\n")
    files = rep["files"]
    size_mb = sum((out / "data" / f).stat().st_size for f in ("train.extxyz", "valid.extxyz", "test.extxyz")) / 1e6
    readme = f"""# {pkg}: MACE pre-relaxer for the package-53 slabs (DRAFT, not staged)

**What it is.** A naive fine-tune of `{Path(a.foundation).name}` on r2SCAN relaxation frames from package 53, so that
rebuilt complexes (docs/PACKAGE53_REBUILD_PLAN.md, step A0) start closer to the r2SCAN minimum. **It is a tool, not a
label model:** its energies are never used as labels, and DFT finishes every structure it touches.

**Why fine-tune.** Unmodified, the foundation model (+ D3) disagrees with DFT at the current package-53 geometries:
force RMSE 0.074-0.085 eV/A, correlation 0.23-0.36, and relaxing on its own surface moves the slab 0.2-0.3 A away while
claiming another 2-3 eV.

**Data** (`data/`, {size_mb:.0f} MB, from `export_prerelax_frames.py`, schema pvpass_prerelax/1, label_grade false):
- train {files['train']['frames']} frames, valid {files['valid']['frames']} (the last 15 % of each training job's
  trajectory), test {files['test']['frames']} (all frames of {', '.join(rep['test_jobs'])}).
- Only complete ionic steps whose SCF reached EDIFF; restart-boundary duplicates removed; {len(rep['rejected'])} steps rejected
  (reasons in dataset.json).
- Target: {target}. **At inference add D3(BJ, r2SCAN) back** (torch-dftd, the INCAR's VDW_S8/A1/A2).
- Source: {rep['package']} (manifest sha256 {rep['manifest_sha256'][:16]}...). PFPACl's first segment and segments
  newer than the export are not in this dataset.

**Copy the data (not through git):** `data/` stays out of the desk repo. From the PV_Passivator machine:
`scp -r data/ <LONI>:<package dir>/data/`. `run_finetune.slurm` refuses to start unless `data/SHA256SUMS` matches.

**Foundation checkpoint on LONI:** `{a.foundation_on_cluster}` (sha256 `{fsha}`); upload it once if absent. No download
happens in the job.

**Run:** `sbatch run_finetune.slurm` (1 x gpu2 GPU, <= {a.time}; {a.epochs} epochs, patience {max(10, a.epochs // 4)},
`--restart_latest`, so a resubmission resumes). Env `{a.env}` (`PRERELAX_MACE_ENV` overrides); the log prints the mace,
torch and CUDA versions. Estimate: a few GPU-hours [P]; one epoch is about {files['train']['frames']} graphs of ~530 atoms.

**PASS (results/test_metrics.json):** on the last 10 frames of each held-out job, force RMSE <= 0.03 eV/A and mean
cosine >= 0.9 for atoms with |F_DFT| > 0.05 eV/A. `test_metrics_foundation.json` is the unmodified foundation for
comparison. The geometry check (relax from a held-out frame with D3 added, compare with the DFT trajectory) runs on the
PV_Passivator machine after export.

**Export:** results/*, logs/*, run/*.model (~ tens of MB), run logs. The model is a custom checkpoint: keep one
canonical copy (e.g. MLIP_PROJECT_STORAGE/Custom_Models/pvpass_prerelax_a0/) and record its sha256.
"""
    lf(out / "README.md", readme)
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    except OSError:
        commit = None
    meta = {"package": pkg, "status": "draft, not staged", "generator": "examples/scripts/make_prerelax_package.py",
            "generator_commit": commit, "dataset": str(ds), "dataset_files": files,
            "foundation_local": str(a.foundation), "foundation_cluster": a.foundation_on_cluster, "foundation_sha256": fsha,
            "files": {p.relative_to(out).as_posix(): sha256(p) for p in sorted(out.rglob("*")) if p.is_file()}}
    lf(out / "package.json", json.dumps(meta, indent=1) + "\n")
    print(json.dumps({"package": str(out), "data_MB": round(size_mb, 1), "frames": {k: v["frames"] for k, v in files.items()}}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
