"""Apply label-acceptance rules to every archived r2SCAN slab run; write docs/r2scan_label_audit.md."""
from pathlib import Path
from pvpassivator.vasp_io import parse_lite
from pvpassivator.recovery import ZVAL_ASSUMED
R = Path("C:/Users/lguts/OneDrive/Desktop/Research/2026/Perovskites/GIEC_Projects/VASP/SCAN")
rows, n_ok = [], 0
for s in ("PbI2_Surf_335_SCAN", "FAI_Surf_335_SCAN"):
    for d in sorted(p for p in (R / s).iterdir() if p.is_dir()):
        r = parse_lite(d)
        if not r.species:
            continue
        bad = r.acceptance(ZVAL_ASSUMED)
        n_ok += not bad
        rows.append(f"| {s.split('_')[0]} | `{d.name}` | {r.cell_charge(ZVAL_ASSUMED):+.0f} | {r.n_ionic} | "
                    f"{'accept' if not bad else 'reject'} | {'; '.join(bad)} |")
txt = ["# r2SCAN archive: label acceptance audit", "",
       "Generated by `examples/scripts/audit_r2scan_labels.py`. Rules: `LiteRun.acceptance` "
       "(odd electrons with ISPIN=1 rejected; charged cells with ISIF>=3 rejected; NSW-limited or "
       "restart-fragment relaxations rejected). Accepted runs are still OutPackLite (no forces), so 'accept' "
       "means *not disqualified*, and every r2SCAN run here used ISIF=4 and no dipole correction.", "",
       f"**{n_ok} of {len(rows)} runs not disqualified.**", "",
       "| Set | Run | q | ionic steps | verdict | reasons |", "|---|---|---|---|---|---|"] + rows
Path("docs/r2scan_label_audit.md").write_text("\n".join(txt) + "\n")
print(n_ok, len(rows))
