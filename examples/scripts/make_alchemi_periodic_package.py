"""Build the LONI GPU package that checks the ALCHEMI batched-MACE backend on PV_Passivator's periodic cells.

    python make_alchemi_periodic_package.py --out DIR --name 129_mace_pvpass_alchemi_parity \
        --pkg53 <53 outputs dir> --acat-pool <adsearch v1_pool dir> --chiral105 <105 outputs dir> \
        --backend <alchemi_backend.py from the adsorbate-search branch> [--min-date 2026-11-07]

Writes, under DIR/NAME:
  inputs/parity/   ~13 cells (53 rev6 bare slab + complexes, ACAT placements, FAPbI3, MBA2PbI4 R and rac) + manifest
  inputs/pool/     the ACAT candidate placements (initial geometries, per-atom ``frozen``) for the timing + manifest
  kit/             alchemi_periodic_check.py and the copied alchemi_backend.py
  run_<NAME>.slurm, export.list, README.md, package.json (files_sha256), inputs/SHA256SUMS

Nothing is submitted.  Models are referenced on the cluster by path and sha256, never copied into the package.
Only 53 relax CONTCARs dated on or after --min-date are used, except the bare slab (task 0 is not part of rev 6;
its accepted relax is the reference all rev-6 complexes were built on), which is listed explicitly.
"""
