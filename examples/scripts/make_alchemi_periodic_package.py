ENV = "/project/lgutsev/env/alchemi_check"
PARITY_53 = ["complex_PEAI", "complex_PEAAc", "complex_TFPAI", "complex_THCl", "complex_PFPACl"]
PARITY_ACAT = ["pool_00_initial", "pool_05_initial", "legacy_MelMel_C"]
POOL_NAMES = [f"pool_{i:02d}" for i in range(11)] + ["legacy_MelMel", "legacy_MelMel_B", "legacy_MelMel_C",
                                                      "one_amineN_endon", "one_flat", "one_ringN_endon"]


def sha(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def mdate(p: Path) -> dt.date:
    return dt.date.fromtimestamp(Path(p).stat().st_mtime)


def acat_mobile_ids(pool: Path):
    """Slab atom ids marked mobile in the adsorbate-search pool (same rule as alchemi_benchmark.load_panel)."""
    for f in sorted((pool / "structures").glob("*.extxyz")):
        if f.stem.endswith("_initial") or f.stem == "ref_molecule":
            continue
        a = read(f)
        if "mobile" in a.arrays and "mol_id" in a.arrays and (a.arrays["mol_id"] > 0).any():
            sub = a.arrays["mol_id"] == 0
            return set(a.arrays["atom_id"][sub & (a.arrays["mobile"] > 0)].tolist())
    raise SystemExit("no labelled pool structure with a 'mobile' array found")


def acat_cell(pool: Path, stem: str, mob_sub: set):
    a = read(pool / "structures" / f"{stem}.extxyz")
    ids = a.arrays["atom_id"] if "atom_id" in a.arrays else np.arange(len(a))
    mol = a.arrays["mol_id"] > 0 if "mol_id" in a.arrays else np.zeros(len(a), bool)
    mobile = mol | np.isin(ids, list(mob_sub))
    return a, ~mobile


def clean(a, frozen=None):
    from ase import Atoms
    b = Atoms(a.get_chemical_symbols(), positions=a.positions, cell=a.cell, pbc=a.pbc)
    if frozen is not None:
        b.set_array("frozen", np.asarray(frozen, int))
    return b


def emit(dirpath: Path, name: str, atoms, src: Path, group: str, extra=None) -> dict:
    f = dirpath / f"{name}.extxyz"
    write(f, atoms, format="extxyz")
    row = {"name": name, "file": f.name, "group": group, "atoms": len(atoms), "source": str(src),
           "source_sha256": sha(src), "source_mtime": mdate(src).isoformat(), "file_sha256": sha(f)}
    row.update(extra or {})
    return row


SLURM = r"""#!/bin/bash
#SBATCH --job-name=pvpass-alchemi
#SBATCH --account=loni_perovsk27
#SBATCH --partition=gpu2
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=8
#SBATCH --gres=gpu:1
#SBATCH --time=05:00:00
#SBATCH --output=logs/%x_%j.out
# __NAME__: ALCHEMI batched-MACE check on PV_Passivator periodic cells.
# (a) float64 single-point parity on every model; (b) only if (a) passes for all of them: native ASE vs toolkit
# batched relax timing, LBFGS then FIRE, three repeats each.
# Generated by PV_Passivator examples/scripts/make_alchemi_periodic_package.py; nothing was submitted by it.
set -eo pipefail
cd "${SLURM_SUBMIT_DIR:?submit from the package directory}"
PKG=$PWD
PY=${ALCHEMI_ENV:-__ENV__}/bin/python
[ -x "$PY" ] || { echo "no env at $PY (shared env, do not rebuild here)" >&2; exit 2; }
OUT=$PKG/results
mkdir -p logs "$OUT" "$OUT/timing"
rm -f "$OUT/DONE" "$OUT/FAILED" "$OUT/status.txt"
trap 'echo "failed at line $LINENO" > "$OUT/FAILED"' ERR
export PYTHONNOUSERSITE=1 TORCHDYNAMO_DISABLE=1 OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK
( cd inputs && sha256sum -c --quiet SHA256SUMS ) || { echo "inputs/ missing or changed" >&2; exit 2; }
{ hostname; date; nvidia-smi; "$PY" -c 'import torch, mace, ase, nvalchemi; print("torch", torch.__version__, torch.cuda.get_device_name(0)); print("mace", mace.__version__, "ase", ase.__version__, "nvalchemi", getattr(nvalchemi, "__version__", "?"))'; } > "$OUT/node.txt" 2>&1
start=$(date +%s)

# ---- models: path + sha256 on the LONI master; ft_v2 is optional (SKIP if absent)
MODELS_OK=""
check_model() {  # check_model TAG PATH SHA REQUIRED
  if [ ! -s "$2" ]; then
    if [ "$4" = 1 ]; then echo "required model missing: $2" >&2; exit 2; fi
    echo "model $1 SKIP (absent: $2)" | tee -a "$OUT/status.txt"; return 0
  fi
  echo "$3  $2" | sha256sum -c --quiet - || { echo "model hash differs: $2" >&2; exit 2; }
  echo "model $1 OK sha256 $3" >> "$OUT/status.txt"
  MODELS_OK="$MODELS_OK $1"
}
__MODEL_CHECKS__
model_path() { case $1 in __MODEL_CASES__ esac; }

# ---- (a) parity, float64, every available model
PARITY_ALL=1
for m in $MODELS_OK; do
  rc=0
  "$PY" -W ignore kit/alchemi_periodic_check.py parity inputs/parity/manifest.json --model "$(model_path $m)" \
      --dtype float64 --out "$OUT/parity_$m.json" > "$OUT/parity_$m.log" 2>&1 || rc=$?
  echo "parity $m exit=$rc" | tee -a "$OUT/status.txt"
  [ $rc -eq 0 ] || PARITY_ALL=0
done

# ---- (b) timing, only if every parity passed
if [ $PARITY_ALL = 1 ]; then
  TM=r2scan; case " $MODELS_OK " in *" ftv2 "*) TM=ftv2;; esac   # the adsorbate-search production model if present
  echo "timing model $TM" >> "$OUT/status.txt"
  for opt in LBFGS FIRE; do
    extra=""; [ $opt = LBFGS ] && extra="--batch1-once"
    rc=0
    "$PY" -W ignore kit/alchemi_periodic_check.py timing inputs/pool/manifest.json --model "$(model_path $TM)" \
        --optimizer $opt --repeats 3 --dtype float32 --fmax 0.05 --steps 500 $extra \
        --out "$OUT/timing" > "$OUT/timing_$opt.log" 2>&1 || rc=$?
    echo "timing $opt exit=$rc" | tee -a "$OUT/status.txt"
  done
else
  echo "timing SKIPPED: parity failed" | tee -a "$OUT/status.txt"
fi
"$PY" -W ignore kit/alchemi_periodic_check.py summary "$OUT" --out "$OUT/summary.json" > "$OUT/summary.log" 2>&1 || true
{ date; echo "wall_s $(( $(date +%s) - start ))"; echo "parity_all_pass $PARITY_ALL"; } > "$OUT/DONE"
cat "$OUT/status.txt"
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--pkg53", type=Path, required=True, help="53_vasp_pvpass_r2scan_eads_v1/outputs")
    ap.add_argument("--acat-pool", type=Path, required=True, help="adsearch v1_pool directory")
    ap.add_argument("--chiral105", type=Path, required=True, help="105_vasp_pvpass_mba2pbi4_chirality_d0/outputs")
    ap.add_argument("--backend", type=Path, required=True, help="alchemi_backend.py (adsorbate-search branch)")
    ap.add_argument("--backend-commit", default="")
    ap.add_argument("--min-date", default="2026-11-07")
    a = ap.parse_args()
    root = a.out / a.name
    if root.exists():
        raise SystemExit(f"{root} exists; remove it first")
    pdir, tdir, kdir = root / "inputs/parity", root / "inputs/pool", root / "kit"
    for d in (pdir, tdir, kdir, root / "logs"):
        d.mkdir(parents=True)
    min_date = dt.date.fromisoformat(a.min_date)

    # ---- parity cells
    rows = []
    slab = a.pkg53 / "slab_FAI_Schot/relax/CONTCAR"
    rows.append(emit(pdir, "p53_slab_FAI_Schot", clean(read(slab)), slab, "53rev6",
                     {"note": "bare-slab reference of rev 6 (task 0 not re-run in rev 6); exempt from the date rule"}))
    for c in PARITY_53:
        f = a.pkg53 / c / "relax/CONTCAR"
        if mdate(f) < min_date:
            raise SystemExit(f"{f} is dated {mdate(f)}, before {min_date}")
        rows.append(emit(pdir, f"p53_{c}", clean(read(f)), f, "53rev6"))
    mob = acat_mobile_ids(a.acat_pool)
    for s in PARITY_ACAT:
        at, fz = acat_cell(a.acat_pool, s, mob)
        rows.append(emit(pdir, f"acat_{s}", clean(at, fz), a.acat_pool / "structures" / f"{s}.extxyz", "acat"))
    bulk = a.pkg53 / "bulk/relax/CONTCAR"
    rows.append(emit(pdir, "bulk_FAPbI3_relaxed", clean(read(bulk)), bulk, "bulk", {"note": "r2SCAN-relaxed 12-atom cell"}))
    rat = clean(read(bulk))
    rat.positions += np.random.default_rng(129).normal(0, 0.05, rat.positions.shape)
    rows.append(emit(pdir, "bulk_FAPbI3_rattled005", rat, bulk, "bulk", {"note": "same cell, rattled 0.05 A (seed 129)"}))
    for c in ("R_fullcell", "rac_fullcell"):
        f = a.chiral105 / c / "relax/CONTCAR"
        rows.append(emit(pdir, f"bulk_MBA2PbI4_{c}", clean(read(f)), f, "bulk", {"note": "package 105 rev1 r2SCAN minimum"}))
    (pdir / "manifest.json").write_text(json.dumps({"purpose": "single-point parity, float64", "cells": rows}, indent=1) + "\n")

    # ---- timing pool: ACAT placements, initial (unrelaxed) geometries, frozen far field
    prow = []
    for s in POOL_NAMES:
        f = a.acat_pool / "structures" / f"{s}_initial.extxyz"
        if not f.exists():
            continue
        at, fz = acat_cell(a.acat_pool, f"{s}_initial", mob)
        prow.append(emit(tdir, s, clean(at, fz), f, "acat", {"free_atoms": int((~fz).sum())}))
    (tdir / "manifest.json").write_text(json.dumps({"purpose": "relax timing pool", "cells": prow}, indent=1) + "\n")

    # ---- kit
    here = Path(__file__).resolve().parent
    shutil.copy2(here / "alchemi_periodic_check.py", kdir / "alchemi_periodic_check.py")
    shutil.copy2(a.backend, kdir / "alchemi_backend.py")

    # ---- slurm
    checks = "\n".join(f'check_model {t} "{p}" {h} {int(r)}' for t, p, h, r in MODELS)
    cases = " ".join(f'{t}) echo "{p}";;' for t, p, _, _ in MODELS)
    slurm = (SLURM.replace("__NAME__", a.name).replace("__ENV__", ENV).replace("__MODEL_CHECKS__", checks)
             .replace("__MODEL_CASES__", cases))
    sname = f"run_{a.name.split('_', 1)[0]}_alchemi.slurm"
    (root / sname).write_bytes(slurm.encode())
    (root / "export.list").write_bytes(b"results/*\nresults/timing/*\nlogs/*\n")

    # ---- LF line endings everywhere (Windows checkouts and ASE text writes can carry CRLF), then checksums
    for f in sorted(root.rglob("*")):
        if f.is_file():
            b = f.read_bytes()
            if b"\r\n" in b:
                f.write_bytes(b.replace(b"\r\n", b"\n"))
    for r in rows + prow:
        r["file_sha256"] = sha((pdir if r in rows else tdir) / r["file"])
    (pdir / "manifest.json").write_bytes((json.dumps({"purpose": "single-point parity, float64", "cells": rows}, indent=1) + "\n").encode())
    (tdir / "manifest.json").write_bytes((json.dumps({"purpose": "relax timing pool", "cells": prow}, indent=1) + "\n").encode())
    sums = []
    for f in sorted((root / "inputs").rglob("*")):
        if f.is_file() and f.name != "SHA256SUMS":
            sums.append(f"{sha(f)}  {f.relative_to(root / 'inputs').as_posix()}")
    (root / "inputs/SHA256SUMS").write_bytes(("\n".join(sums) + "\n").encode())

    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=here, capture_output=True, text=True).stdout.strip()
    except Exception:  # noqa: BLE001
        commit = ""
    readme = f"""# {a.name}

ALCHEMI (nvalchemi-toolkit 0.3.0) batched-MACE check on PV_Passivator's own periodic cells. One GPU job.

    mkdir -p logs
    sbatch {sname}

1. **Parity (float64)** for every model whose file is present with the right sha256: native MACECalculator twice
   (yardstick) against toolkit batch of 1, batch of N ({len(rows)} cells, {sum(r['atoms'] for r in rows)} atoms), shuffled order,
   and two different batch compositions. PASS: every toolkit comparison within 1e-6 eV and 1e-6 eV/A.
2. **Timing**, only if every parity passed: pool of {len(prow)} ACAT placements ({prow[0]['atoms'] if prow else '?'} atoms each,
   far field frozen), native ASE one at a time vs toolkit fixed batches (cells per batch from a memory probe,
   peak <= 50 % VRAM), float32, fmax 0.05 eV/A, cap 500 steps, three repeats; LBFGS (ASE LBFGS vs nvalchemi
   LBFGS) then FIRE (ASE FIRE vs nvalchemi FIRE2). Model: ACAT ft_v2 if present, else MACE-matpes-r2scan-omat-ft.
   Batched end points are re-checked with the native calculator (untimed).

Models (cluster path, sha256; ft_v2 optional):
""" + "\n".join(f"- `{p}` `{h}`{'' if r else ' (optional: SKIP if absent)'}" for _, p, h, r in MODELS) + f"""

Environment: shared `{ENV}` (not rebuilt), `TORCHDYNAMO_DISABLE=1`, gpu2, 1 GPU, 8 CPUs, 5 h walltime, no --mem.
Results: `results/` (parity_*.json, timing/timing_LBFGS.json, timing/timing_FIRE.json, summary.json, status.txt,
node.txt, DONE or FAILED). Estimate 1.5-3 GPU node-h [I].
"""
    (root / "README.md").write_bytes(readme.encode())
    files = {f.relative_to(root).as_posix(): sha(f) for f in sorted(root.rglob("*")) if f.is_file() and f.name != "package.json"}
    pkg = {"package": a.name, "status": "staged, not submitted", "created": dt.date.today().isoformat(),
           "generator": "examples/scripts/make_alchemi_periodic_package.py", "generator_commit": commit,
           "backend_source": {"file": "alchemi_backend.py", "branch": "acat-adsearch", "commit": a.backend_commit,
                              "sha256": sha(a.backend)},
           "slurm": sname, "env": ENV, "models": [{"tag": t, "path": p, "sha256": h, "required": r} for t, p, h, r in MODELS],
           "parity_cells": rows, "timing_pool": prow, "estimate_gpu_node_h": "1.5-3 [I]", "files_sha256": files}
    (root / "package.json").write_bytes((json.dumps(pkg, indent=1) + "\n").encode())
    print(f"built {root}: {len(rows)} parity cells, {len(prow)} pool cells")


if __name__ == "__main__":
    main()
